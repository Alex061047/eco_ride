  <h1 class="mb-4">Charte de Protection des Données Personnelles</h1>

  <section class="mb-5">
    <h2>1. Introduction</h2>
    <p>Chez <strong>Ecoride</strong>, nous attachons une grande importance à la protection de votre vie privée et de vos données personnelles. Conformément au Règlement Général sur la Protection des Données (RGPD) et aux recommandations de la CNIL, cette charte vous informe sur la manière dont nous collectons, utilisons, stockons et protégeons vos données.</p>
  </section>

  <section class="mb-5">
    <h2>2. Données collectées</h2>
    <p>Nous pouvons être amenés à collecter différentes catégories de données, notamment :</p>
    <ul>
      <li><strong>Données d'identification</strong> : nom, prénom, adresse email, téléphone.</li>
      <li><strong>Données financières</strong> : informations liées au paiement.</li>
      <li><strong>Données liées à l'utilisation du service</strong> : historique de covoiturages, avis déposés, interactions avec notre support.</li>
    </ul>
  </section>

  <section class="mb-5">
    <h2>3. Finalités de traitement</h2>
    <p>Vos données sont collectées pour :</p>
    <ul>
      <li>Créer et gérer votre compte utilisateur.</li>
      <li>Gérer vos trajets, réservations et paiements.</li>
      <li>Répondre à vos demandes (support, réclamations).</li>
      <li>Publier et gérer vos avis/commentaires.</li>
      <li>Améliorer l'expérience utilisateur et la sécurité.</li>
      <li>Respecter nos obligations légales et réglementaires.</li>
    </ul>
  </section>

  <section class="mb-5">
    <h2>4. Base légale des traitements</h2>
    <ul>
      <li><strong>Votre consentement</strong> : pour les avis, newsletters, cookies non essentiels.</li>
      <li><strong>L'exécution d'un contrat</strong> : pour l'ouverture de votre compte, la gestion des covoiturages.</li>
      <li><strong>Notre intérêt légitime</strong> : pour assurer la sécurité du site, améliorer nos services.</li>
      <li><strong>Une obligation légale</strong> : archivage, comptabilité, réponse aux réquisitions.</li>
    </ul>
  </section>

  <section class="mb-5">
    <h2>5. Durée de conservation</h2>
    <ul>
      <li>Pendant la durée strictement nécessaire aux finalités.</li>
      <li>Jusqu'à 3 ans à compter du dernier contact en l'absence d'activité.</li>
      <li>Jusqu'à 10 ans pour les obligations comptables ou probatoires.</li>
      <li>Les avis, logs et données techniques peuvent être archivés ou anonymisés.</li>
    </ul>
  </section>

  <section class="mb-5">
    <h2>6. Destinataires des données</h2>
    <p>Vos données sont exclusivement accessibles par :</p>
    <ul>
      <li>Le personnel habilité de <strong>Ecoride</strong>.</li>
      <li>Nos prestataires techniques (hébergement, emailing, paiement sécurisé).</li>
      <li>Éventuellement, des partenaires agissant sous notre autorité et dans le respect du RGPD.</li>
    </ul>
    
  </section>

  <section class="mb-5">
    <h2>7. Sécurité des données</h2>
    <p>Nous mettons en œuvre des mesures techniques et organisationnelles robustes :</p>
    <ul>
      <li>Stockage sécurisé des données.</li>
      <li>Contrôle d'accès aux serveurs.</li>
      <li>Sauvegardes régulières.</li>
      <li>Sensibilisation et formation de nos équipes au RGPD.</li>
    </ul>
  </section>

  <section class="mb-5">
    <h2>8. Vos droits</h2>
    <p>Conformément au RGPD, vous disposez de :</p>
    <ul>
      <li><strong>Droit d'accès</strong> : obtenir une copie de vos données.</li>
      <li><strong>Droit de rectification</strong> : modifier des données inexactes.</li>
      <li><strong>Droit à l'effacement</strong> (dans certains cas).</li>
      <li><strong>Droit à la limitation du traitement</strong>.</li>
      <li><strong>Droit d'opposition</strong> (traitements basés sur l'intérêt légitime).</li>
      <li><strong>Droit à la portabilité</strong> de vos données.</li>
      <li><strong>Droit de retirer votre consentement</strong> à tout moment.</li>
      <li><strong>Droit d'introduire une réclamation</strong> auprès de la CNIL.</li>
    </ul>
    <p>Nous répondons à toute demande dans un délai maximum de 30 jours.</p>
  </section>

